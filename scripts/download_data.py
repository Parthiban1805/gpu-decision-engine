"""Download public GPU-cluster traces (PLAN.md §2.1, phase P1).

For each dataset: read its README, follow the access path it describes, verify upstream
checksums where the README provides them, and write data/raw/<name>/SOURCES.md. Failures are
logged and do not stop other datasets. Large datasets marked `requires_confirmation` need
--confirm-large.

    python tasks.py data                         # enabled datasets
    python tasks.py data --datasets helios
    python tasks.py data --datasets philly --confirm-large
"""

from __future__ import annotations

import argparse
import sys
import traceback
from pathlib import Path

import yaml

from gde import paths
from gde.ingestion.download import DatasetResult, Fetcher, append_log, write_sources_md

RAW = paths.DATA / "raw"
LOG = RAW / "download_log.jsonl"


def write_status(results: dict[str, DatasetResult], cfgs: dict[str, dict]) -> Path:
    lines = ["# Dataset acquisition status", "",
             "Generated by `python tasks.py data`. Per-dataset details in `<name>/SOURCES.md`.", "",
             "| Dataset | Status | Detail |", "|---|---|---|"]
    for name, cfg in cfgs.items():
        res = results.get(name)
        if res is None:
            sources = RAW / name / "SOURCES.md"
            text = sources.read_text(encoding="utf-8") if sources.exists() else ""
            status_line = next((ln for ln in text.splitlines() if ln.startswith("- Status:")), "")
            if cfg.get("requires_confirmation") and "downloaded" not in status_line:
                status, detail = "awaiting_confirmation", "large dataset; needs user approval (--confirm-large)"
            elif sources.exists():
                status = status_line.removeprefix("- Status:").strip().strip("*").split("**")[0] or "unknown"
                detail = "from previous run; see SOURCES.md"
            else:
                status, detail = "skipped", cfg.get("skip_reason", "not run")
        else:
            status = res.status
            detail = res.error or (f"{sum(f.kind == 'download' for f in res.files)} files downloaded, "
                                   f"{sum(f.kind == 'extracted' for f in res.files)} extracted")
        lines.append(f"| {name} | {status} | {' '.join(str(detail).split())} |")
    path = RAW / "DOWNLOADS.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def main() -> int:
    cfgs: dict[str, dict] = yaml.safe_load((paths.CONFIGS / "datasets.yaml").read_text(encoding="utf-8"))["datasets"]
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--datasets", nargs="+", choices=sorted(cfgs), help="default: all enabled")
    ap.add_argument("--tables", nargs="+", help="alibaba2020 tables (default from config)")
    ap.add_argument("--confirm-large", action="store_true", help="allow datasets marked requires_confirmation")
    ap.add_argument("--force", action="store_true", help="re-download even if files verify")
    args = ap.parse_args()

    selected = args.datasets or [n for n, c in cfgs.items() if c.get("enabled")]
    results: dict[str, DatasetResult] = {}
    for name in selected:
        cfg = cfgs[name]
        out = RAW / name
        if "github" not in cfg:
            res = DatasetResult(name=name, status="skipped", error=cfg.get("skip_reason"))
        elif cfg.get("requires_confirmation") and not args.confirm_large:
            res = DatasetResult(name=name, status="awaiting_confirmation",
                                error="large dataset; re-run with --confirm-large after the user approves")
            write_sources_md(res, cfg, out)
        else:
            print(f"== {name}", flush=True)
            fetcher = Fetcher(name, cfg, out, force=args.force)
            try:
                res = fetcher.run(args.tables if name == "alibaba2020" else None)
            except Exception as exc:  # noqa: BLE001 - log any failure and continue with other datasets
                res = fetcher.result
                res.status, res.error = "failed", f"{type(exc).__name__}: {exc}"
                traceback.print_exc()
            write_sources_md(res, cfg, out)
        append_log(LOG, res)
        results[name] = res
        print(f"   {name}: {res.status}" + (f" ({res.error})" if res.error else ""), flush=True)

    print(f"status: {write_status(results, cfgs).relative_to(paths.REPO_ROOT)}")
    return 0 if any(r.status == "downloaded" for r in results.values()) or not results else 1


if __name__ == "__main__":
    sys.exit(main())
